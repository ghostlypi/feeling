"""Generate early loader markup from local assets (also works in a standalone checkout)."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent
HEAD_START = '<!-- Critical loader styles (generated by sync_loader.py) -->'
HEAD_END = '<!-- End critical loader styles -->'
BODY_START = '<!-- Early loader (generated by sync_loader.py) -->'
BODY_END = '<!-- End early loader -->'


def div_end(html, start):
    """Find a div's end without depending on its number of nested children."""
    depth = 0
    for tag in re.finditer(r'<(/?)div\b[^>]*>', html[start:]):
        depth += -1 if tag[1] else 1
        if depth == 0:
            return start + tag.end()
    raise ValueError('Unclosed loader div')


def render_page(html, css, js):
    html = re.sub(re.escape(HEAD_START) + r'.*?' + re.escape(HEAD_END), '', html, flags=re.S)
    html = re.sub(r'\s*<link\b[^>]*href="(?:\.\./)*css/loader\.css"[^>]*>', '', html)
    html = re.sub(r'\s*<script src="(?:\.\./)*js/loader\.js"></script>', '', html)
    fallback = []

    def stylesheet(match):
        tag = match.group()
        if not re.search(r'rel="stylesheet"', tag):
            return tag
        tag = re.sub(r'\s+media="print"', '', tag)
        tag = re.sub(r'\s+onload="this\.media=\x27all\x27"', '', tag)
        if not re.search(r'href="[^"]+"', tag):
            return tag
        tag = re.sub(r'\s*/?>$', '>', tag)
        fallback.append(tag)
        return re.sub(r'\s*/?>$', ' media="print" onload="this.media=\x27all\x27">', tag)

    head, rest = html.split('</head>', 1)
    head = re.sub(r'<link\b[^>]*>', stylesheet, head)
    critical = (HEAD_START + '\n<style>' + css + '</style>\n'
                '<noscript><style>#loader-wrapper{display:none}'
                '#loader-wrapper[data-loader-mode="persistent"]{display:flex}</style>'
                + ''.join(fallback) + '</noscript>\n' + HEAD_END)
    html = head.rstrip() + '\n' + critical + '\n</head>' + rest

    wrapper = re.search(r'<div\b[^>]*\bid="loader-wrapper"[^>]*>', html)
    wrapper_end = div_end(html, wrapper.start())
    markup = html[wrapper.start():wrapper_end]
    container = re.search(r'<div\b[^>]*\bclass="loader-container"[^>]*>', markup)
    if not container:
        raise ValueError('Missing loader container')
    container_end = div_end(markup, container.start())
    markup = (markup[:container.start()] + '<div class="loader-container"></div>'
              + markup[container_end:])
    body = BODY_START + '\n' + markup + '\n<script>' + js + '</script>\n' + BODY_END
    if BODY_START in html:
        return re.sub(re.escape(BODY_START) + r'.*?' + re.escape(BODY_END), lambda _: body, html, flags=re.S)
    return html[:wrapper.start()] + body + html[wrapper_end:]


def sync_pages(root=ROOT, check=False):
    root = Path(root)
    output = Path('dist')
    config = root / 'web.json'
    if config.exists():
        output = Path(json.loads(config.read_text()).get('build', {}).get('output', 'dist'))
    css = (root / 'css/loader.css').read_text()
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    css = re.sub(r'\s+', ' ', css).strip()
    js = (root / 'js/loader.js').read_text()
    js = re.sub(r'<!--.*?-->', '', js, flags=re.S)
    js = '\n'.join(line.strip() for line in js.splitlines()
                   if line.strip() and not line.lstrip().startswith('//'))
    updated = []
    for page in sorted(root.rglob('*.html')):
        relative = page.relative_to(root)
        if (any(part.startswith('.') or part in ('node_modules', 'tests', 'legacy') for part in relative.parts)
                or relative.is_relative_to(output)):
            continue
        raw = page.read_bytes()
        original = raw.decode()
        if 'id="loader-wrapper"' not in original:
            continue
        newline = '\r\n' if b'\r\n' in raw else '\n'
        try:
            result = render_page(original.replace('\r\n', '\n'), css, js).replace('\n', newline)
        except ValueError as error:
            raise ValueError(f'{page}: {error}') from error
        if result != original:
            if not check:
                page.write_bytes(result.encode())
            updated.append(page.relative_to(root))
    return updated


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Report stale inline loaders without writing')
    args = parser.parse_args()
    stale = []
    manifest = ROOT / 'framework-manifest.json'
    if args.check and manifest.exists():
        for name, digest in json.loads(manifest.read_text())['files'].items():
            asset = ROOT / name
            if not asset.is_file() or hashlib.sha256(asset.read_bytes()).hexdigest() != digest:
                stale.append(name)
        for name in stale:
            print(f'Shared asset differs from framework manifest: {name}')
    changed = sync_pages(check=args.check)
    for page in changed:
        print(page)
    raise SystemExit(1 if args.check and (changed or stale) else 0)
