"""Install the shared theme and terms controller on complete HTML pages."""
import html as html_module
import json
from pathlib import Path
import re

HEAD_START = '<!-- Shared UI (generated by sync_ui.py) -->'
HEAD_END = '<!-- End shared UI -->'
DEFAULT_TERMS = 'https://parthiyer.com/policy/tnc.html'
DEFAULT_REJECTED = 'https://parthiyer.com/policy/rejected.html'


def render_page(html, prefix='', consent=None, assets=None):
    if not re.search(r'</head\s*>', html, re.I) or not re.search(r'<body\b', html, re.I):
        return html  # Keep generated fragments and redirects without a document body intact.
    consent = consent or {}
    html = re.sub(re.escape(HEAD_START) + r'.*?' + re.escape(HEAD_END) + r'\n?', '', html, flags=re.S)
    # Replace the previous per-site controllers and cookie dialog styles.
    html = re.sub(r'\s*<script\b[^>]*\bsrc=[\"\'](?:\./|\.\./|/)*(?:js/)?(?:theme|consent)\.js[\"\'][^>]*>\s*</script>', '', html, flags=re.I)
    html = re.sub(r'\s*<link\b[^>]*\bhref=[\"\'](?:\./|\.\./|/)*css/cookie-consent\.css[\"\'][^>]*>', '', html, flags=re.I)
    # The LAN revocation page cannot request assets from the revoked origin.
    inline = '<!-- Self-contained on purpose:' in html
    if inline:
        html = re.sub(r'<script>\s*// Light/dark toggle.*?</script>', '', html, flags=re.S)
    # Retire only the known legacy consent containers, preserving surrounding content.
    pattern = r'<div\b[^>]*\bid=[\"\'](?:cookie-consent-popup|consent-overlay|tnc-consent-popup)[\"\'][^>]*>'
    while match := re.search(pattern, html, re.I):
        depth = 0
        for tag in re.finditer(r'<(/?)div\b[^>]*>', html[match.start():], re.I):
            depth += -1 if tag[1] else 1
            if depth == 0:
                html = html[:match.start()] + html[match.start() + tag.end():]
                break
        else:
            raise ValueError('Unclosed legacy consent container')
    terms = html_module.escape(consent.get('terms_url', DEFAULT_TERMS), quote=True)
    rejected = html_module.escape(consent.get('rejected_url', DEFAULT_REJECTED), quote=True)
    options = f'data-terms-url="{terms}" data-rejected-url="{rejected}"'
    if inline:
        if assets is None:
            raise ValueError('Self-contained pages require shared UI assets')
        block = (HEAD_START + '\n<style>' + assets['css/consent.css'] + '</style>\n'
                 '<script>' + assets['js/theme.js'] + '</script>\n'
                 f'<script {options}>' + assets['js/consent.js'] + '</script>\n'
                 + HEAD_END + '\n')
    else:
        block = (HEAD_START + '\n'
                 f'<link rel="stylesheet" href="{prefix}css/consent.css" media="print" onload="this.media=\x27all\x27">\n'
                 f'<script src="{prefix}js/theme.js"></script>\n'
                 f'<script src="{prefix}js/consent.js" {options} defer></script>\n'
                 + HEAD_END + '\n')
    # Keep this before the loader block so both generators remain idempotent.
    marker = '<!-- Critical loader styles (generated by sync_loader.py) -->'
    end = html.index(marker) if marker in html else re.search(r'</head\s*>', html, re.I).start()
    return html[:end].rstrip() + '\n' + block + html[end:]


def sync_pages(root, check=False, assets=None):
    root = Path(root)
    config_path = root / 'web.json'
    config = json.loads(config_path.read_text()) if config_path.exists() else {}
    output = Path(config.get('build', {}).get('output', 'dist'))
    if assets is None:
        assets = {name: (root / name).read_text() for name in ('css/consent.css', 'js/theme.js', 'js/consent.js')}
    changed = []
    for page in sorted(root.rglob('*.html')):
        relative = page.relative_to(root)
        if (any(part.startswith('.') or part in ('node_modules', 'tests', 'legacy') for part in relative.parts)
                or relative.is_relative_to(output)):
            continue
        raw = page.read_bytes()
        original = raw.decode()
        newline = '\r\n' if b'\r\n' in raw else '\n'
        prefix = '../' * (len(relative.parts) - 1)
        result = render_page(original.replace('\r\n', '\n'), prefix, config.get('consent'), assets).replace('\n', newline)
        if original != result:
            changed.append(relative)
            if not check:
                page.write_bytes(result.encode())
    return changed
